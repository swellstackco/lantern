// Headless (muted) run of the simulator. Usage: node scripts/e2e-sim.mjs [outDir]
import { chromium } from "playwright-core";
import { mkdirSync } from "node:fs";
const out = process.argv[2] ?? "e2e-shots";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", args: ["--mute-audio"] });
const page = await browser.newPage({ viewport: { width: 1720, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://localhost:5173");
await page.getByText("MCP connected").waitFor({ timeout: 15000 });
await page.getByLabel("Alexa voice").uncheck();
const say = async (t) => { await page.getByLabel("What Rose says").fill(t); await page.getByRole("button", { name: "Send" }).click(); await page.waitForTimeout(1200); };
await page.screenshot({ path: `${out}/0-home.png` });
await say("Alexa, good morning");
await page.screenshot({ path: `${out}/1-morning.png` });
await say("Not great, maybe five hours.");
await say("It's Wednesday");
await page.screenshot({ path: `${out}/2-words.png` });
await say("ok");
await page.screenshot({ path: `${out}/3-done.png` });
await say("Show Maya the trend");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/4-trend.png` });
await say("show the doctor summary");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/5-doctor.png` });
await page.getByRole("button", { name: "Close" }).click();
await page.getByRole("tab", { name: "JSON-RPC" }).click();
await page.screenshot({ path: `${out}/6-rpc.png` });
await page.getByRole("tab", { name: "Talk" }).click();
await say("Alexa, good afternoon");
await page.screenshot({ path: `${out}/7-midday.png` });
await say("apple and river"); await say("dog cat horse cow pig"); await say("She won second place");
await page.screenshot({ path: `${out}/8-midday-done.png` });
await say("any updates for Maya?"); await say("add a visit Friday 10 am");
await page.getByRole("tab", { name: "Outbox" }).click(); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/9-outbox.png` });
console.log("errors:", errors.length ? errors : "none");
await browser.close();
